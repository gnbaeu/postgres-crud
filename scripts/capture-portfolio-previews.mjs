// Writes genuine, optimized WebP assets and the manifest only after both captures succeed.
// Use ONLY an isolated temporary browser profile; never attach a personal profile.
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { connectBrowser, localOrigin } from "./browser-session.mjs";
const origin=localOrigin();
const browser=await connectBrowser();
try {
  await browser.send("Storage.clearDataForOrigin",{origin,storageTypes:"all"});
  await browser.send("Page.addScriptToEvaluateOnNewDocument",{source:`localStorage.setItem('gnwaa-welcome-v1','done');localStorage.setItem('ganbat-customer-language','en');localStorage.setItem('gnwaa-pixel-zen-v1',JSON.stringify({appearance:'light'}));localStorage.setItem('gnwaa-japan-experience-v1',JSON.stringify({motion:'off'}));`});
  await browser.viewport(1200,900);
  await browser.navigate(origin+"/");
  const hero=await browser.evaluate("(()=>{const r=document.querySelector('.pz-intro').getBoundingClientRect();return {x:0,y:0,width:1200,height:Math.ceil(r.bottom+24),scale:1};})()");
  const platform=await browser.screenshot(null,{clip:hero,full:false,format:"webp",quality:82});
  await browser.navigate(origin+"/randomizer/movie");
  await browser.click("#rz-draw");
  await browser.wait("!!document.querySelector('[data-result-id]') && !document.querySelector('.rz-drawing')","real movie result");
  await browser.evaluate("window.scrollTo(0,0)");
  const randomizer=await browser.screenshot(null,{full:false,format:"webp",quality:82});
  for(const image of [platform,randomizer]){
    assert.equal(image.toString("ascii",0,4),"RIFF");assert.equal(image.toString("ascii",8,12),"WEBP");
  }
  const directory=resolve("public/images/projects");
  await mkdir(directory,{recursive:true});
  await writeFile(resolve(directory,"gnwaa-platform.webp"),platform);
  await writeFile(resolve(directory,"randomizer.webp"),randomizer);
  const previews={
    gnwaa:{src:"/images/projects/gnwaa-platform.webp",width:1200,height:hero.height,sourcePath:"/"},
    randomizer:{src:"/images/projects/randomizer.webp",width:1200,height:900,sourcePath:"/randomizer/movie"}
  };
  await writeFile(resolve("portfolio-previews.js"),"// Actual local browser captures generated by npm run capture:portfolio.\nexport const PROJECT_PREVIEWS = "+JSON.stringify(previews,null,2)+";\n");
  console.log("Actual project captures saved:",directory);
  console.log("WebP sizes:",platform.length,randomizer.length,"bytes. Manifest updated.");
} finally {await browser.close();}
